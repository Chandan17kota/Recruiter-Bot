-- Recruiter Bot schema (PostgreSQL 14+). Hand-written DDL, safe to re-run.
--
-- Matches are NOT stored: they are derived from these tables plus configurable
-- weights and computed per request, so a stored table would go stale.

CREATE TABLE IF NOT EXISTS candidates (
  id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug             TEXT NOT NULL UNIQUE CHECK (slug <> '' AND slug = lower(btrim(slug))),
  full_name        TEXT NOT NULL CHECK (btrim(full_name) <> ''),
  experience_years NUMERIC(4,1) NOT NULL CHECK (experience_years >= 0 AND experience_years <= 60),
  availability     TEXT CHECK (availability IN ('immediate','two_weeks','not_looking')),
                   -- NULL = unknown, which is NOT the same as not_looking
  traits_known     BOOLEAN NOT NULL DEFAULT TRUE,   -- FALSE = trait data unknown
  quirk            TEXT,                            -- display-only, never scored
  created_at       TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS jobs (
  id                   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug                 TEXT NOT NULL UNIQUE CHECK (slug <> '' AND slug = lower(btrim(slug))),
  title                TEXT NOT NULL CHECK (btrim(title) <> ''),
  min_experience_years NUMERIC(4,1) NOT NULL DEFAULT 0
                       CHECK (min_experience_years >= 0 AND min_experience_years <= 60),
  tagline              TEXT,                        -- display-only, never scored
  created_at           TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Vocabularies: normalized + non-empty only; no character whitelist (c++, c#, .net are legal).
CREATE TABLE IF NOT EXISTS skills (
  id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL UNIQUE
       CHECK (name <> '' AND name = lower(btrim(name)) AND name !~ '\s{2,}')
);

CREATE TABLE IF NOT EXISTS traits (
  id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL UNIQUE
       CHECK (name <> '' AND name = lower(btrim(name)) AND name !~ '\s{2,}')
);

CREATE TABLE IF NOT EXISTS candidate_skills (
  candidate_id INTEGER NOT NULL REFERENCES candidates(id) ON DELETE CASCADE,
  skill_id     INTEGER NOT NULL REFERENCES skills(id)     ON DELETE RESTRICT,
  PRIMARY KEY (candidate_id, skill_id)
);

CREATE TABLE IF NOT EXISTS candidate_traits (
  candidate_id INTEGER NOT NULL REFERENCES candidates(id) ON DELETE CASCADE,
  trait_id     INTEGER NOT NULL REFERENCES traits(id)     ON DELETE RESTRICT,
  PRIMARY KEY (candidate_id, trait_id)
);

CREATE TABLE IF NOT EXISTS job_required_skills (
  job_id   INTEGER NOT NULL REFERENCES jobs(id)   ON DELETE CASCADE,
  skill_id INTEGER NOT NULL REFERENCES skills(id) ON DELETE RESTRICT,
  PRIMARY KEY (job_id, skill_id)
);

-- Culture keywords share the traits vocabulary so they can be compared directly.
CREATE TABLE IF NOT EXISTS job_culture_keywords (
  job_id   INTEGER NOT NULL REFERENCES jobs(id)   ON DELETE CASCADE,
  trait_id INTEGER NOT NULL REFERENCES traits(id) ON DELETE RESTRICT,
  PRIMARY KEY (job_id, trait_id)
);

-- The composite PKs already cover lookups by candidate_id / job_id.
-- These support FK checks and reverse lookups (who has skill X?).
CREATE INDEX IF NOT EXISTS idx_candidate_skills_skill  ON candidate_skills (skill_id);
CREATE INDEX IF NOT EXISTS idx_candidate_traits_trait  ON candidate_traits (trait_id);
CREATE INDEX IF NOT EXISTS idx_job_req_skills_skill    ON job_required_skills (skill_id);
CREATE INDEX IF NOT EXISTS idx_job_culture_trait       ON job_culture_keywords (trait_id);
CREATE INDEX IF NOT EXISTS idx_candidates_availability ON candidates (availability);
